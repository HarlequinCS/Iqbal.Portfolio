#!/usr/bin/env python3
"""Pre-deploy build for saifuliqbal.io. Standard library only; run from anywhere:

    python3 tools/build.py          # update files in place
    python3 tools/build.py --check  # change nothing; exit 1 if anything is out of date

It does three things:
1. Asset versions: rewrites ?v=... on links to css/*.css and js/main.js to a short
   hash of the file, so Cloudflare and browsers fetch new CSS/JS after every change.
2. sitemap.xml: lists every page whose <link rel="canonical"> points at itself and
   that is not marked noindex. <lastmod> is the date of the page's last git commit
   (or today, for a page with uncommitted changes). Pages are found automatically,
   so a new page only needs a canonical link to appear in the sitemap.
3. CSP hashes: computes the sha256 of every inline <script> (not JSON-LD) and checks
   that .htaccess and the nginx snippet allow exactly those hashes. A mismatch
   blocks the theme/motion script and silently disables the animations.
"""
import base64, datetime, hashlib, pathlib, re, subprocess, sys
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = "https://saifuliqbal.io"
NGINX_SNIPPET = pathlib.Path("/etc/nginx/snippets/portfolio-security-headers.conf")
SKIP = {"wip.html"}
# Images worth associating with a page in Google Images (page path -> image paths).
PAGE_IMAGES = {"/": ["images/saiful-iqbal.webp"], "/about": ["images/saiful-iqbal.webp"]}

CHECK = "--check" in sys.argv
problems, changed = [], []


def pages():
    return sorted(p for p in ROOT.rglob("*.html")
                  if ".git" not in p.parts and p.name not in SKIP and "tools" not in p.parts)


def write(path, new):
    if path.read_text(encoding="utf-8") != new:
        changed.append(str(path.relative_to(ROOT)))
        if not CHECK:
            path.write_text(new, encoding="utf-8")


# 1. Asset versions -------------------------------------------------------------
def short_hash(rel):
    return hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()[:10]


ASSET = re.compile(r'((?:href|src)=")((?:\.\./)?)((?:css/[\w.-]+\.css|js/main\.js))(?:\?v=[\w]+)?(")')
for page in pages():
    text = page.read_text(encoding="utf-8")
    write(page, ASSET.sub(lambda m: f"{m[1]}{m[2]}{m[3]}?v={short_hash(m[3])}{m[4]}", text))


# 2. Sitemap ----------------------------------------------------------------------
def lastmod(path):
    rel = str(path.relative_to(ROOT))
    try:
        dirty = subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain", "--", rel],
                               capture_output=True, text=True, check=True).stdout.strip()
        if not dirty:
            out = subprocess.run(["git", "-C", str(ROOT), "log", "-1", "--format=%cs", "--", rel],
                                 capture_output=True, text=True, check=True).stdout.strip()
            if out:
                return out
    except (OSError, subprocess.CalledProcessError):
        pass
    return datetime.date.today().isoformat()


entries = []
for page in pages():
    text = page.read_text(encoding="utf-8")
    robots = re.search(r'<meta name="robots" content="([^"]*)"', text)
    if robots and "noindex" in robots[1]:
        continue
    canon = re.search(r'<link rel="canonical" href="([^"]+)"', text)
    if not canon:
        problems.append(f"{page.relative_to(ROOT)}: indexable page has no canonical link")
        continue
    url = canon[1]
    rel = "/" + str(page.relative_to(ROOT))
    expected = SITE + re.sub(r"(index)?\.html$", "", rel)
    if url != expected:
        problems.append(f"{rel}: canonical {url} does not match its clean URL {expected}")
        continue
    entries.append((url, lastmod(page), PAGE_IMAGES.get(url[len(SITE):], [])))

entries.sort(key=lambda e: (e[0] != SITE + "/", e[0]))
lines = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<!-- Generated by tools/build.py. Do not edit by hand. -->',
         '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
         'xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">']
for url, mod, images in entries:
    lines.append(f"  <url>\n    <loc>{escape(url)}</loc>\n    <lastmod>{mod}</lastmod>")
    for img in images:
        lines.append(f"    <image:image><image:loc>{SITE}/{img}</image:loc></image:image>")
    lines.append("  </url>")
lines.append("</urlset>\n")
sitemap = ROOT / "sitemap.xml"
new_map = "\n".join(lines)
old_map = sitemap.read_text(encoding="utf-8") if sitemap.exists() else ""
if CHECK:
    # Only dates moving is not a reason to fail --check: the URL list is what matters.
    undated = lambda s: re.sub(r"<lastmod>.*?</lastmod>", "", s)
    if undated(old_map) != undated(new_map):
        changed.append("sitemap.xml")
elif old_map != new_map:
    changed.append("sitemap.xml")
    sitemap.write_text(new_map, encoding="utf-8")


# 3. CSP hashes ----------------------------------------------------------------------
hashes = set()
for page in pages():
    for body in re.findall(r"<script>(.*?)</script>", page.read_text(encoding="utf-8"), re.S):
        hashes.add("sha256-" + base64.b64encode(hashlib.sha256(body.encode()).digest()).decode())
for conf in (ROOT / ".htaccess", NGINX_SNIPPET):
    if not conf.exists():
        continue
    allowed = set(re.findall(r"'(sha256-[A-Za-z0-9+/=]+)'", conf.read_text()))
    if allowed != hashes:
        problems.append(f"{conf}: CSP allows {sorted(allowed)} but pages need {sorted(hashes)}")

# Report ------------------------------------------------------------------------------
for c in changed:
    print(("out of date: " if CHECK else "updated: ") + c)
for p in problems:
    print("PROBLEM: " + p, file=sys.stderr)
print(f"sitemap: {len(entries)} URLs")
sys.exit(1 if problems or (CHECK and changed) else 0)
